export const MAX_LEVEL = 10000;

// 解放レベル：前半ほど早く、後半ほど間隔が広い（最後の製品が Lv.10000）
function unlockLevel(i) {
  if (i === 0) return 1;
  return Math.round(2 + (MAX_LEVEL - 2) * Math.pow(i / 99, 1.6));
}

// 卸値：1品進むごとに約1.15倍＋系統が上がるごとに上乗せ
function basePrice(i) {
  return 12 * Math.pow(1.15, i) * (1 + Math.floor(i / 10) * 0.6);
}

// 取引先：系統が上がるほど増えるが、こだわり品(奇数)は半分
function baseBuyers(i) {
  const n = 3 + Math.floor(i * 1.6);
  return i % 2 === 1 ? Math.max(2, Math.round(n * 0.5)) : n;
}

export const PRODUCTS = SERIES.flatMap((s, si) =>
  s.items.map((name, vi) => {
    const id = si * 10 + vi;
    const niche = id % 2 === 1;
    const buyers = baseBuyers(id);
    return {
      id,
      name,
      series: s.name,
      seriesIndex: si,
      price: Math.round(basePrice(id) * (niche ? 1.35 : 1) * 100) / 100,
      buyers,
      demand: buyers * DEMAND_PER_BUYER,
      unlock: unlockLevel(id),
      colors: s.colors,
      niche,
    };
  }),
);
